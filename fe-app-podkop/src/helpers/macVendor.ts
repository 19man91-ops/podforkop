export function normalizeMac(value?: string | null): string {
  const raw = `${value || ''}`
    .trim()
    .toLowerCase()
    .replace(/[^0-9a-f]/g, '');
  if (raw.length !== 12) return '';
  return raw.match(/.{2}/g)!.join(':').toUpperCase();
}

export function isLocallyAdministeredMac(mac: string): boolean {
  const first = parseInt((mac || '').split(':')[0], 16);
  return Number.isFinite(first) && (first & 0x02) !== 0;
}

export function getMacVendor(mac: string): string {
  const normalized = normalizeMac(mac);
  if (!normalized) return '';
  return OUI_VENDORS[normalized.slice(0, 8).replace(/:/g, '')] || '';
}
